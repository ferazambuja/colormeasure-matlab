function assertSessionCompatible(classInfo)
%ASSERTSESSIONCOMPATIBLE Refuse mixed or older loaded session code safely.
% Internal launcher guard; metadata lookup does not create a
% session or operate equipment. Optional metadata checks a retained handle.
% MATLAB can retain an old class while newer functions resolve on the path:
% https://www.mathworks.com/help/matlab/matlab_oop/organizing-classes-in-folders.html
% Fernando Voltolini de Azambuja, 2026.
if nargin == 0, classInfo = matlab.metadata.Class.fromName('colormeasure.session.Session'); end
required = {'configuration','workspaceName','adapterKey','preparation', ...
    'settingsCatalog','settingsOverrides','settingsSnapshot','lastSettingsReceipt','SavedSnapshot'};
expected = fullfile(fileparts(mfilename('fullpath')), 'Session.m');
resolved = which('colormeasure.session.Session');
compatible = ~isempty(classInfo) && ...
    all(ismember(required, {classInfo.PropertyList.Name})) && ...
    ~any(ismember({'connectionReadiness','prepareChartReference','keepChartPosition'}, ...
        {classInfo.MethodList.Name}));
if ~compatible || ~strcmp(resolved, expected)
    error('Measurement:SessionCompatibility', ...
        ['MATLAB has older or mixed colormeasure.session.Session code loaded. ' ...
        'Existing sessions and readings were not changed. Preserve needed results ' ...
        'from session.measurements and session.files, finish the old batch, then ' ...
        'restart MATLAB with only one colormeasure installation and retry. ' ...
        'If the old process must remain open, use a separate fresh MATLAB process. ' ...
        'Inspect duplicate paths with which(''colormeasure.session.Session'',''-all''). ' ...
        'Resolved Session: %s. Expected: %s.'], resolved, expected);
end
end
