function data = validateViewData(data, count)
%VALIDATEVIEWDATA Check an adapter's viewData result against its documented contract.
%   DATA describes COUNT readings as one struct. XYZ is COUNT-by-3 or empty;
%   spectra has COUNT cells, each empty or a struct with x and y; hasSpectra
%   is a logical scalar; per-reading arrays are vectors with COUNT entries.
%   Empty vectors are accepted for an empty batch; row and column vectors remain unchanged.
%   Absent optional fields are valid. Errors use Measurement:InvalidViewData.
%   Fernando Voltolini de Azambuja, 2026.
assert(isstruct(data) && isscalar(data), 'Measurement:InvalidViewData', ...
    'The adapter viewData hook must return a struct.');
assert(~isfield(data,'previewWhiteXYZ'),'Measurement:InvalidViewData', ...
    'Native reading previews do not accept a source white. Select a Lab white in Compare, or derive an adapted color in Color.');
if isfield(data, 'XYZ')
    xyz = data.XYZ;
    assert(isnumeric(xyz) && (isempty(xyz) || (ismatrix(xyz) && isequal(size(xyz), [count 3]))), ...
        'Measurement:InvalidViewData', 'viewData.XYZ must be empty or %d-by-3.', count);
end
if isfield(data, 'spectra')
    spectra = data.spectra;
    assert(iscell(spectra) && numel(spectra) == count && (isempty(spectra) || isvector(spectra)), ...
        'Measurement:InvalidViewData', 'viewData.spectra must be a cell vector with %d entries.', count);
    for index = 1:numel(spectra)
        item = spectra{index};
        assert(isempty(item) || (isstruct(item) && isscalar(item) && all(isfield(item, {'x','y'}))), ...
            'Measurement:InvalidViewData', ...
            'viewData.spectra{%d} must be empty or a struct with x and y.', index);
    end
end
if isfield(data, 'hasSpectra')
    assert(islogical(data.hasSpectra) && isscalar(data.hasSpectra), ...
        'Measurement:InvalidViewData', 'viewData.hasSpectra must be a logical scalar.');
end
for name = {'observer','observerId','spectralLabel','spectralXLabel','spectralUnits','noSpectrumReason'}
    if isfield(data, name{1})
        assert(colormeasure.session.isText(data.(name{1})), 'Measurement:InvalidViewData', ...
            'viewData.%s must be text.', name{1});
    end
end
perReading = {'spectralLabels','observerNames','observerIds','spectralUnitsByReading', ...
    'spectralQuantities','xyzSources','xyzUnitsByReading', ...
    'xyzComparisonKeys','chromaticityComparisonKeys','spectralComparisonKeys', ...
    'xyzScaleDeclarationKeys','reflectanceRatioReasons','measurementConditions', ...
    'spectralSampling','spectralSamplingSources','provenances','measurementModes'};
for name = perReading
    if isfield(data, name{1})
        value = data.(name{1});
        assert(iscell(value) && numel(value) == count && (isempty(value) || isvector(value)) && ...
            all(cellfun(@(v) isempty(v) || colormeasure.session.isText(v), value(:))), ...
            'Measurement:InvalidViewData', ...
            'viewData.%s must be a cell vector of %d text entries.', name{1}, count);
    end
end
if isfield(data, 'reflectanceRatioEligible')
    eligible = data.reflectanceRatioEligible;
    assert(islogical(eligible) && numel(eligible) == count && (isempty(eligible) || isvector(eligible)), ...
        'Measurement:InvalidViewData', ...
        'viewData.reflectanceRatioEligible must be a logical vector with %d entries.', count);
end
assert(~any(isfield(data,{'recordKinds','scalarQuantities','scalarUnits','scalarValues', ...
    'stimulusIds','stimulusDescriptions','operationStatuses','displayIds', ...
    'displayUpdateDelayMs','instrumentReactionMs'})), 'Measurement:InvalidViewData', ...
    'This installation displays direct XYZ and spectral readings; these additional record fields are unsupported.');
end
