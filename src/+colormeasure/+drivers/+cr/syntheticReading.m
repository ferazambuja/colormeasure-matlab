function reading = syntheticReading(model,index,intent)
%SYNTHETICREADING Explicit illustrative data; no device identity or raw replies.
if nargin<3, intent=struct([]); end
[key,label] = colormeasure.drivers.cr.modelInfo(model);
step = 1;
if strcmp(key,'CR250'), step=2; end
wavelength = (380:step:780).';
profile = colormeasure.simulation.syntheticProfile(index,wavelength,intent);
[xyz,total] = colormeasure.drivers.cr.spectralValues(profile.spectrum,wavelength);
[cct,duv] = colormeasure.drivers.cr.cct(xyz);
stored = colormeasure.drivers.cr.storedText();
reading = struct('XYZ',xyz,'deviceType',label, ...
    'xyzMethod',stored.synthetic, ...
    'xyzUnits',stored.syntheticXYZUnits,'observerId','CIE1931_2deg', ...
    'lambda',wavelength,'spectralData',profile.spectrum(:), ...
    'spectralQuantity',stored.syntheticQuantity,'spectralUnits',stored.syntheticSpectralUnits, ...
    'spectralUnitsConfirmed',false,'instrumentXYZ',NaN(1,3), ...
    'instrumentMetadata',struct(),'driverSnapshot',struct(), ...
    'CCT',cct,'Duv',duv, ...
    'cctSource','Synthetic colormeasure.colorimetry.XYZ2CCT, CIE 1960 UCS, MCSL compatibility table', ...
    'integratedSpectrum',total,'radiometricType',NaN, ...
    'isSynthetic',true,'syntheticProfile',profile.name,'syntheticProfileIndex',profile.index, ...
    'syntheticAssociation',profile.association,'syntheticSeed',profile.seed,'syntheticGain',profile.gain);
if strcmp(key,'CR100')
    % Internal SPD generates synthetic XYZ only; CR-100 does not measure SPD.
    reading.lambda = zeros(0,1); reading.spectralData = zeros(0,1);
    reading.spectralQuantity = ''; reading.spectralUnits = '';
    reading.integratedSpectrum = NaN;
end
end
