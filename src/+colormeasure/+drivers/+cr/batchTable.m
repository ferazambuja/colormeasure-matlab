function data = batchTable(readings,batchInfo)
%BATCHTABLE One row per spectral sample; CR-100 retains one row per reading.
% Native metadata, raw replies and original array shapes remain in the MAT.
tables = cell(numel(readings),1);
for index = 1:numel(readings)
    r = readings(index);
    hasSpectrum = ~isempty(r.lambda);
    count = max(1,numel(r.lambda));
    wavelength = NaN(count,1); spectrum = NaN(count,1);
    if hasSpectrum, wavelength=r.lambda(:); spectrum=r.spectralData(:); end
    text = @(value) repmat({char(value)},count,1);
    number = @(value) repmat(value,count,1);
    tables{index} = table(number(index),text(r.name),text(r.notes), ...
        text(r.deviceType),number(hasSpectrum),wavelength,spectrum, ...
        number(r.XYZ(1)),number(r.XYZ(2)),number(r.XYZ(3)), ...
        number(r.instrumentXYZ(1)),number(r.instrumentXYZ(2)),number(r.instrumentXYZ(3)), ...
        text(r.xyzMethod),text(r.xyzUnits),text(r.observerId), ...
        text(r.spectralQuantity),text(r.spectralUnits),number(r.spectralUnitsConfirmed), ...
        number(r.integratedSpectrum),number(r.CCT),number(r.Duv),text(r.cctSource), ...
        number(r.isSynthetic),text(r.startedAtUTC),text(r.completedAtUTC), ...
        text(r.startedAtLocal),text(r.completedAtLocal), ...
        text(r.localTimeZone),text(r.port), ...
        text(batchInfo.startedAtUTC),text(batchInfo.completedAtUTC), ...
        'VariableNames',{'MeasurementIndex','MeasurementName','Notes','DeviceType', ...
        'HasSpectrum','Wavelength_nm','SpectralReading','X','Y','Z', ...
        'Instrument_X','Instrument_Y','Instrument_Z','XYZMethod','XYZUnits','Observer', ...
        'SpectralQuantity','SpectralUnits','SpectralUnitsConfirmed','IntegratedSpectrum', ...
        'CCT_K','Duv_1960','CCTSource','IsSynthetic','StartedAtUTC','CompletedAtUTC', ...
        'StartedAtLocal','CompletedAtLocal','LocalTimeZone','Port', ...
        'BatchStartedAtUTC','BatchCompletedAtUTC'});
end
if isempty(tables), data=table; else, data=vertcat(tables{:}); end
end
