function adapter = uiAdapter(model,varargin)
%UIADAPTER Add presentation and explicit automatic UI acquisition settings.
% Fernando Voltolini de Azambuja, 2026.
[key,~] = colormeasure.drivers.cr.modelInfo(model);
adapter = colormeasure.drivers.cr.adapter(key,varargin{:});
adapter.workspaceName = ['colorMeasure' key 'Session'];
adapter.viewData = @(readings) colormeasure.drivers.cr.viewData(readings,key);
adapter.settings = struct('catalog',colormeasure.drivers.cr.settingsControls(key), ...
    'read',@(meter) meter.readSettings(), ...
    'apply',@(meter,overrides) meter.applyAutomaticSettings(overrides));
adapter.preparation.headings{end+1} = 'Acquisition settings';
adapter.preparation.details{end+1} = ['Measure uses the model''s automatic acquisition recipe. ' ...
    'Choose Settings... to open Measurement settings for deliberate overrides and help about each control. ' ...
    'Read settings shows the current setup; Use for next readings stages your choices. ' ...
    'They are applied before the next reading. Accessory and correction selections stay ' ...
    'unchanged unless you override them.'];
if ~strcmp(key,'CR100')
    adapter.preparation.headings{end+1} = 'Object color view';
    adapter.preparation.details{end+1} = ['For object color, open the Color tab and choose View > Reflectance / relight with the ' ...
        'measured white reference and its spectral reflectance data. An ideal-white assumption ' ...
        'gives a relative ratio. Selecting a Lab comparison white alone does not perform this step.'];
end
end
