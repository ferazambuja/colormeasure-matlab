function controls = settingsControls(model)
%SETTINGSCONTROLS Return model-specific settings help without instrument I/O.
%   Dynamic choices, bounds and availability come from readCapabilities or
%   readSettings. Aperture and CR100 mode are read-only observations.
%   This static catalog never invents a device option ID.
%   Sources: Colorimetry Research Remote Communications Manual v1.36 (R) and
%   CRI App Manual v1.5.10 (A), available at
%   https://www.colorimetryresearch.com/downloads. See docs/drivers/cr/settings.md.

key = colormeasure.drivers.cr.modelInfo(model);
controls = colormeasure.session.settingsControl();

if strcmp(key, 'CR100')
    controls(end+1,1) = control('mode', 'Measurement mode', 'choice', ...
        'Read-only observation of the current instrument measurement mode.', ...
        'Check that an ordinary XYZ reading uses Colorimeter mode.', ...
        'Temporal acquisition is a separate workflow; this control does not enable Flicker or Response Time acquisition.', ...
        'The automatic recipe first selects the device-reported Colorimeter mode. An unavailable or ambiguous mode prevents automatic application.', ...
        'R 4.2.1.6, p.14 (firmware 1.16 onward); A 5.8, p.20.');
end

controls(end+1,1) = control('exposureMode', 'Exposure mode', 'choice', ...
    'Automatic selects the integration time; Fixed (the CR manual also calls it Manual) uses a specified time.', ...
    'Use Automatic for ordinary measurements; use Fixed for a controlled exposure experiment.', ...
    'Longer integration increases duration and changes temporal averaging. CR100 Fixed exposure requires Fixed electronic range D.', ...
    'The automatic recipe selects the device-reported Auto option.', ...
    'R 4.2.1.7-8, pp.14-15; A 5.8, p.20 and 5.10, p.23.');
if ~strcmp(key, 'CR100')
    controls(end).help.tradeoff = ...
        'Longer integration increases duration and changes temporal averaging.';
end

controls(end+1,1) = control('exposureMs', 'Exposure time (ms)', 'number', ...
    'Integration time used when exposure mode is Fixed.', ...
    'Set an explicit time when controlling integration is part of the experiment.', ...
    'A short exposure may give unstable low-light readings; integration time is not the complete acquisition duration.', ...
    'Leave unset for automatic exposure. Fixed exposure requires a value within the reported exposure limits.', ...
    'R 4.2.1.8, p.15 and 4.3.2.20-21, p.46.');

if strcmp(key, 'CR100')
    controls(end+1,1) = control('rangeMode', 'Electronic range mode', 'choice', ...
        'Automatic selects the electronic range; Fixed (the CR manual also calls it Manual) uses a selected range.', ...
        'Use Automatic ordinarily; use Fixed for range comparisons or with Fixed exposure.', ...
        'An unsuitable range can produce over-range or under-range errors. Fixed exposure requires range D.', ...
        'The automatic recipe selects the device-reported Auto option.', ...
        'R 4.2.1.10-11, p.16; A 5.8, p.20.');
    controls(end+1,1) = control('range', 'Electronic range', 'choice', ...
        'Electronic range used when range mode is Fixed.', ...
        'Choose a reported range deliberately; choose D when using Fixed exposure.', ...
        'Changing range can alter sensitivity and the usable signal range.', ...
        'Leave unset when using automatic range selection.', ...
        'R 4.2.1.11, p.16 and 4.3.2.10, p.41; A 5.8, p.20.');
end

switch key
    case 'CR100'
        multiplier = control('exposureMultiplier', 'Exposure multiplier', 'number', ...
            'Makes the exposure a multiple of its base exposure.', ...
            'Consider a longer exposure when investigating variable low-light readings from a stable source.', ...
            'Increases measurement duration. It is not documented as a count of independently averaged readings.', ...
            'Preserve the current multiplier unless explicitly overridden; the automatic recipe does not set it to one.', ...
            'R 4.2.1.14, p.17; A 5.8, p.20.');
    case 'CR250'
        multiplier = control('exposureMultiplier', 'Averages', 'number', ...
            'Repeats and averages exposures using the specified multiplier.', ...
            'Use additional averages to investigate random variation on a stable source.', ...
            'More averages take longer; source changes during the sequence are also averaged.', ...
            'Preserve the current multiplier unless explicitly overridden; automatic exposure does not reset averaging.', ...
            'R 4.2.1.14, p.17; A 5.10, p.23.');
    case 'CR300'
        multiplier = control('exposureMultiplier', 'Exposure multiplier', 'number', ...
            'Sets the multiplier reported by the remote protocol.', ...
            'Use only with an established CR300 procedure for the installed firmware.', ...
            'Its detailed timing behavior requires model confirmation; CR250 averaging semantics are not assumed.', ...
            'Preserve the current multiplier unless explicitly overridden.', ...
            'R 4.2.1.14, p.17; A 5.10 describes CR250, not CR300.');
end
controls(end+1,1) = multiplier;

controls(end+1,1) = control('syncMode', 'Synchronize with light source', 'choice', ...
    'Controls whether capture follows a detected or specified light modulation frequency.', ...
    'Use for a periodically modulated source when its timing is relevant to the measurement.', ...
    'Automatic detection can fail. Synchronization changes temporal sampling, not only noise.', ...
    'Preserve the current mode unless explicitly overridden; automatic exposure does not select synchronization.', ...
    'R 4.2.1.12-13, pp.16-17 and 4.3.2.11, pp.42-43; A 5.8, p.20.');
controls(end+1,1) = control('syncFrequencyHz', 'Synchronization frequency (Hz)', 'number', ...
    'Light modulation frequency used when synchronization mode is Manual.', ...
    'Enter an established source frequency within the reported limits.', ...
    'An incorrect frequency can sample the source inconsistently; a display refresh label may not describe its light modulation.', ...
    'Leave unset unless Manual synchronization is explicitly selected.', ...
    'R 4.2.1.13, p.17 and 4.3.2.22-23, p.47.');

if ~strcmp(key, 'CR100')
    controls(end+1,1) = control('speed', 'Measurement speed', 'choice', ...
        'Selects a supported spectroradiometer measurement speed.', ...
        'The CR250 application manual recommends Slow for low light; use only speeds reported by this meter.', ...
        'Speed affects acquisition duration; faster modes do not establish equal low-light precision.', ...
        'Preserve the current speed unless explicitly overridden; there is no assumed Auto speed.', ...
        'R 4.2.1.19, p.19 and 4.3.2.26, p.48; A 5.10, p.23 (CR250).');
    if strcmp(key, 'CR300')
        controls(end).help.whenToUse = ...
            'Choose a reported speed using an established procedure for the installed meter and light level.';
    end
end

controls(end+1,1) = control('accessory', 'Attached accessory', 'choice', ...
    'Selects the fitted accessory and its measurement quantity.', ...
    'Change only to match the calibrated accessory physically fitted to the meter.', ...
    'The selection can change units and available correction profiles. Check that the fitted accessory matches the selection before measuring.', ...
    'Preserve the current selection unless explicitly overridden.', ...
    'R 4.2.1.1, p.12 and 4.3.2.4, p.39; A 5.8, p.20 and 5.10, p.23.');
controls(end+1,1) = control('aperture', 'Physical aperture', 'choice', ...
    'Read-only fitted-aperture text reported by RS Aperture.', ...
    'Check the measurement field and spot size against the intended target geometry.', ...
    'Physical aperture describes the optical field, not the CIE observer. This API has no aperture setter.', ...
    'Read the current observation in readSettings().values.aperture; this control always remains unavailable for editing.', ...
    'R 4.3.3.3, p.50; https://www.colorimetryresearch.com/products/cr-250 and /products/cr-300');
if ~strcmp(key, 'CR100')
    controls(end).help.meaning = ...
        'Read-only fitted-aperture text from RS Aperture; the physical aperture is fixed when the meter is ordered.';
end
for slot = 1:3
    controls(end+1,1) = control(sprintf('filter%d', slot), ...
        sprintf('Attached ND filter %d', slot), 'choice', ...
        'Selects one calibrated neutral-density filter physically fitted to the meter.', ...
        'Match the software selection to the installed filter; ND filters extend the measurable intensity range.', ...
        'Selecting a filter in software does not install it. The protocol has conflicting examples for clearing a filter.', ...
        'Preserve the current selection; only reported filter IDs are eligible, with no fabricated None option.', ...
        'R 4.2.1.2-4, pp.12-13 and 4.2.1.23, p.21; https://www.colorimetryresearch.com/accessories/nd-filters');
end

controls(end+1,1) = control('userCalibrationMode', 'Existing correction mode', 'choice', ...
    'Enables an existing user correction supported by the meter.', ...
    'Use a correction prepared for the source, accessory and reference procedure.', ...
    'Corrections change measured results; selecting a profile does not create or validate a calibration.', ...
    'Preserve the current mode unless explicitly overridden; ordinary acquisition does not disable corrections.', ...
    'R 4.2.1.16-18, pp.18-19; A 12.2.3, pp.77-78 and 14.3.1, pp.83-84.');
if strcmp(key, 'CR100')
    controls(end+1,1) = control('matrixId', 'Existing matrix correction', 'choice', ...
        'Selects an existing colorimeter correction matrix for the selected accessory.', ...
        'Use an established matrix when Matrix correction mode is selected.', ...
        'Matrix applicability depends on the source and accessory; a matching name alone does not establish calibration.', ...
        'Preserve the existing matrix unless explicitly overridden; this control does not create or overwrite one.', ...
        'R 4.2.1.17, p.18 and 4.3.2.15, p.44; A 12.2.3, pp.77-78.');
end
controls(end+1,1) = control('matchId', 'Existing match correction', 'choice', ...
    'Selects an existing match correction supported by the meter.', ...
    'Use an established profile when Match correction mode is selected.', ...
    'CR100 XYZ matching and CR250 spectral matching are different operations; do not assume identical CR300 profile semantics.', ...
    'Preserve the existing match unless explicitly overridden; this control does not create or overwrite one.', ...
    'R 4.2.1.18, p.19 and 4.3.2.16, p.45; A 14.3.1.1-2, pp.83-84.');
switch key
    case 'CR100'
        controls(end).help.meaning = 'Selects an existing XYZ match correction.';
        controls(end).help.tradeoff = ...
            'The correction changes instrument XYZ and requires a suitable reference procedure.';
    case 'CR250'
        controls(end).help.meaning = 'Selects an existing spectral match correction.';
        controls(end).help.tradeoff = ...
            'The correction changes the spectrum and derived values; use a suitable spectral reference procedure.';
    case 'CR300'
        controls(end).help.tradeoff = ...
            'Confirm profile semantics for the installed meter; a generic Match label alone does not establish them.';
end

controls(end+1,1) = control('maxAutoExposureMs', 'Maximum automatic exposure (ms)', 'number', ...
    'Limits integration time while exposure mode is Automatic; documented since firmware 1.26.', ...
    'Use an explicit limit when integration duration must be bounded for the experiment.', ...
    'A lower limit can affect low-light results. No current-setting RS readback is documented, so a successful write is acknowledged only.', ...
    'Preserve the existing limit unless explicitly overridden; a host response deadline does not set this value.', ...
    'R 4.2.1.9, p.15 and 4.3.1.10, p.26; A 5.8, p.20.');
end

function item = control(id, label, type, meaning, whenToUse, tradeoff, normal, source)
% Static CR controls start unavailable; readCapabilities/readSettings enable them.
item = colormeasure.session.settingsControl(id, label, type, struct('value', {}, 'label', {}), NaN, NaN, false, ...
    struct('meaning', meaning, 'whenToUse', whenToUse, 'tradeoff', tradeoff, 'normal', normal, 'source', source));
end
