function reading = reading(snapshot,index)
%READING Value-only adapter record from a retained native CR snapshot row.
% Omit index for the newest row. Index selects acquired values and their own
% identity/provenance; it never computes quantities or changes the snapshot.
count = size(snapshot.XYZ,1);
if nargin < 2, index = count; end
if count == 0 || numel(snapshot.metadata) ~= count || ...
        ~isnumeric(index) || ~isreal(index) || ~isscalar(index) || ...
        ~isfinite(index) || index ~= fix(index) || index < 1 || index > count
    error('CR:AdapterReading','A complete CR reading and metadata row are required.');
end
meta = snapshot.metadata(index);
reading = struct('readingId',meta.readingId,'XYZ',snapshot.XYZ(index,:), ...
    'deviceType',meta.identity.model,'xyzMethod',meta.xyzSource, ...
    'xyzUnits',meta.xyzUnit,'observerId','CIE1931_2deg', ...
    'lambda',zeros(0,1),'spectralData',zeros(0,1), ...
    'spectralQuantity',meta.radiometricQuantity, ...
    'spectralUnits',meta.spectralDensityUnit, ...
    'spectralUnitsConfirmed',meta.spectralDensityUnitsConfirmed, ...
    'instrumentXYZ',snapshot.instrumentXYZ(index,:), ...
    'instrumentMetadata',meta,'driverSnapshot',snapshot, ...
    'CCT',snapshot.CCT(index),'Duv',snapshot.Duv(index),'cctSource',meta.cctSource, ...
    'integratedSpectrum',NaN,'radiometricType',meta.radiometricType, ...
    'isSynthetic',false,'syntheticProfile','','syntheticProfileIndex',NaN);
if isfield(snapshot,'spectralData')
    reading.lambda = snapshot.wl(index,:).';
    reading.spectralData = snapshot.spectralData(index,:).';
    reading.integratedSpectrum = snapshot.integratedSpectrum(index);
end
end
