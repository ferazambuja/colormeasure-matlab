function guide = preparation(model)
%PREPARATION Model-specific operating help without instrument or UI calls.
% CRI App Manual 1.5.10 sections 5.8, 5.10, 7.2.3; Remote Manual 1.36.
% https://www.colorimetryresearch.com/downloads
% White-reference substitution: NIST SP250-71, p.2 eq.(2.1).
% https://www.nist.gov/document/sp25071-colorimeterpdf
% This is the host workflow, not a reproduction of CRIApp's integrated ratio.
% See docs/drivers/cr/preparation.md for operating steps and sources.
% Fernando Voltolini de Azambuja, 2026.
[key,label] = colormeasure.drivers.cr.modelInfo(model);
guide = struct('title',[label ' preparation'], ...
    'summary','Match the accessory and target geometry, and keep the source stable.', ...
    'details',{{}},'url','https://www.colorimetryresearch.com/downloads', ...
    'required',true);
setup = ['Aim at the intended target, keep the source stable, and match the selected ' ...
    'accessory and filters to the fitted hardware. Follow the installed model instructions ' ...
    'for startup and maintenance.'];
switch key
    case 'CR100'
        modelSetup = ['CR-100 measures XYZ. For ordinary readings, select Colorimeter mode ' ...
            'and use automatic exposure and electronic range. ' ...
            'Fixed exposure requires Fixed range D. Choose ' ...
            'synchronization deliberately for a modulated source. A cosine receptor ' ...
            'changes the measured quantity to illuminance.'];
        correction = ['If using a matrix or XYZ match correction, check that the active ' ...
            'profile was prepared for the source and accessory.'];
    case 'CR250'
        modelSetup = ['CR-250 has a fixed aperture chosen when ordered; check spot size ' ...
            'and working distance. Use automatic exposure for ordinary readings. Slow ' ...
            'speed is intended for low light; additional averages increase duration. ' ...
            'A cosine receptor changes the quantities to illuminance and irradiance.'];
        correction = ['If using a spectral match correction, check that the active ' ...
            'profile was prepared for the reference procedure.'];
    case 'CR300'
        modelSetup = ['CR-300 has a fixed aperture chosen when ordered; check spot size ' ...
            'and working distance. Use automatic exposure for ordinary readings. ' ...
            'Choose a reported speed and exposure multiplier appropriate for the ' ...
            'experiment. A cosine receptor changes the quantities ' ...
            'to illuminance and irradiance.'];
        correction = ['If using a correction, check the active profile and follow an ' ...
            'established procedure for the installed meter and profile.'];
end
if strcmp(key,'CR100')
    reflectance = ['Object color: keep external illumination and geometry fixed and measure ' ...
        'a reference and sample in a defined setup. CR-100 has no spectrum, so spectral ' ...
        'reflectance and relighting are unavailable. A comparison white is not a calibration.'];
else
    reflectance = ['Object color: under stable external illumination, measure a white reference ' ...
        'and the object with matching geometry, accessory, settings and wavelength grid. ' ...
        'Use calibrated reference spectral data for a separate host calculation; an ideal-white assumption ' ...
        'gives a relative ratio. Selecting a comparison white alone does not do this.'];
end
acquisition = ['Check the selected measurement settings before starting. Keep the ' ...
    'target steady until acquisition finishes, and save the reading with its capture settings.'];
guide.details = {setup,modelSetup,acquisition,reflectance,correction};
guide.headings = {'Target and accessories','Model setup','Taking a reading', ...
    'Object color','Existing corrections'};
end
