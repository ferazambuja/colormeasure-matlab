function adapter = uiAdapter(varargin)
%UIADAPTER Add presentation and explicit automatic UI acquisition settings.
%   Fernando Voltolini de Azambuja, 2026.
adapter = colormeasure.drivers.cs2000.adapter(varargin{:});
adapter.workspaceName = 'colorMeasureCS2000Session';
adapter.viewData = @colormeasure.drivers.cs2000.viewData;
adapter.settings = struct('catalog',colormeasure.drivers.cs2000.settingsCatalog(), ...
    'read',@(meter) meter.readSettings(), ...
    'apply',@(meter,overrides) meter.applyAutomaticSettings(overrides));
adapter.preparation.headings{end+1} = 'Acquisition settings';
adapter.preparation.details{end+1} = ['Choose Settings... to open Measurement settings, then Read settings to ' ...
    'inspect the current setup. Use for next readings stages overrides, which are applied ' ...
    'before the next reading.'];
adapter.preparation.headings{end+1} = 'Object color view';
adapter.preparation.details{end+1} = ['For object color, open the Color tab and choose View > Reflectance / relight with the measured ' ...
    'white reference and its spectral reflectance data. An ideal-white assumption gives a ' ...
    'relative ratio; a Lab comparison white alone does not perform this step.'];
end
