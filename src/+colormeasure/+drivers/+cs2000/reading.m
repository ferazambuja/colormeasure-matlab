function reading = reading(snapshot,index)
%READING Value-only adapter record from a retained native CS-2000 snapshot.
% Omit index for the newest reading. Preserve its own identity, capture
% conditions, instrument XYZ and spectrum; do not normalize or recalculate.
count = size(snapshot.XYZData,2);
if nargin < 2, index = count; end
if count == 0 || size(snapshot.spectralData,2) ~= count || ...
        numel(snapshot.metadata) ~= count || ~isnumeric(index) || ...
        ~isreal(index) || ~isscalar(index) || ~isfinite(index) || ...
        index ~= fix(index) || index < 1 || index > count
    error('CS2000:AdapterReading','A complete CS-2000 reading and metadata column are required.');
end
metadata = snapshot.metadata(index);
stored = colormeasure.drivers.cs2000.storedText();
reading = struct('readingId',metadata.readingId,'XYZ',reshape(snapshot.XYZData(:,index),1,3), ...
    'deviceType',metadata.identity.model,'xyzMethod',metadata.acquisition.xyzSource, ...
    'xyzUnits',stored.xyzUnits,'xyzUnitsConfirmed',false,'observerId','CIE1931_2deg', ...
    'lambda',snapshot.wavelengths,'spectralData',snapshot.spectralData(:,index), ...
    'spectralQuantity','radiance','spectralUnits',stored.spectralUnits, ...
    'spectralUnitsConfirmed',true,'driverSnapshot',snapshot, ...
    'instrumentMetadata',metadata,'isSynthetic',false, ...
    'cleanupStatus',struct(),'warnings',{{}});
end
