function conditions = conditions(payload)
%CONDITIONS MEDR condition fields, Rev.7 p.44. Integration time is in us.
% The external ND filter is field 6; aperture and calibration are 7 and 8.
% observer=0 records the host's fixed XYZ block 01 selection. It is not a
% ninth MEDR condition or a read of the instrument display's OBSR setting.
% https://www.konicaminolta.com.cn/instruments/download/software/driver/cs-20002000a_cs0700_eng.pdf
v = colormeasure.drivers.cs2000.numbers(payload,8);
if any(v ~= fix(v)) || ~ismember(v(1),0:4) || ~ismember(v(2),0:2) || ...
        v(3) <= 0 || v(3) > 999999999 || ~ismember(v(4),0:1) || ...
        ~ismember(v(5),0:1) || ~ismember(v(6),0:2) || ...
        ~ismember(v(7),0:2) || ~ismember(v(8),0:10)
    error('CS2000:Conditions', 'Measurement conditions contain values outside the documented ranges.');
end
angles = [1 0.2 0.1];
conditions = struct('speedMode',v(1),'syncMode',v(2), ...
    'integrationTime',v(3)/1e6,'internalNDFilter',v(4), ...
    'closeupLens',v(5),'externalNDFilter',v(6),'measurementAngle',v(7), ...
    'measurementAngleDegrees',angles(v(7)+1), ...
    'userCalibrationChannel',v(8),'observer',0);
end
