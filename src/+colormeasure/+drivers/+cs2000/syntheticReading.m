function reading = syntheticReading(index,intent)
%SYNTHETICREADING Generated software preview; not an instrument measurement.
% No transport, identity query, serial number, firmware or raw replies exist.
% Its units are labelled synthetic; no instrument establishes them, so both
% confirmation flags are false.
if nargin<2, intent=struct([]); end
lambda = (380:780)';
profile = colormeasure.simulation.syntheticProfile(index,lambda,intent);
stored = colormeasure.drivers.cs2000.storedText();
reading = struct('XYZ',reshape(colormeasure.colorimetry.spectra2XYZ(profile.spectrum,lambda),1,3), ...
    'deviceType','CS-2000', ...
    'xyzMethod',stored.syntheticXYZMethod, ...
    'xyzUnits',stored.syntheticXYZUnits,'xyzUnitsConfirmed',false, ...
    'observerId','CIE1931_2deg','lambda',lambda,'spectralData',profile.spectrum, ...
    'spectralQuantity','radiance','spectralUnits',stored.syntheticSpectralUnits, ...
    'spectralUnitsConfirmed',false,'driverSnapshot',struct(), ...
    'instrumentMetadata',struct(),'isSynthetic',true, ...
    'cleanupStatus',struct(),'warnings',{{}}, ...
    'syntheticProfile',profile.name,'syntheticProfileIndex',profile.index, ...
    'syntheticDescription',profile.description,'syntheticAssociation',profile.association, ...
    'syntheticSeed',profile.seed,'syntheticGain',profile.gain);
end
