function data = batchTable(readings, batchInfo)
%BATCHTABLE Long-format CSV with raw XYZ and explicit source/unit columns.
% The batch MAT file retains complete native snapshots and raw metadata;
% the CSV is a convenient numeric/text view, not a replacement archive.
names = {'MeasurementIndex','MeasurementName','Notes','StartedAtUTC','CompletedAtUTC', ...
    'DeviceType','Port','Wavelength_nm','SpectralReading','Raw_X','Raw_Y','Raw_Z', ...
    'XYZSource','XYZUnits','Observer','SpectralQuantity','SpectralUnits','IsSynthetic', ...
    'Warnings','MATLABVersion','MeasurementDurationSeconds', ...
    'BatchStartedAtUTC','BatchCompletedAtUTC','BatchElapsedSeconds'};
types = repmat({'string'},1,numel(names));
types([1 8:12 21 24]) = {'double'};
types{18} = 'logical';
data = table('Size',[0 numel(names)],'VariableTypes',types,'VariableNames',names);
parts = cell(numel(readings),1);
for index = 1:numel(readings)
    reading = readings(index);
    count = numel(reading.lambda);
    assert(numel(reading.spectralData) == count && numel(reading.XYZ) == 3, ...
        'CS2000:ExportReading','CSV requires aligned spectrum and XYZ values.');
    repeat = @(value) repmat(string(value),count,1);
    number = @(value) repmat(double(value),count,1);
    warnings = strjoin(reading.warnings,' | ');
    synthetic = isequal(reading.isSynthetic,true);
    parts{index} = table(number(index),repeat(reading.name),repeat(reading.notes), ...
        repeat(reading.startedAtUTC),repeat(reading.completedAtUTC), ...
        repeat(reading.deviceType),repeat(reading.port), ...
        double(reading.lambda(:)),double(reading.spectralData(:)), ...
        number(reading.XYZ(1)),number(reading.XYZ(2)),number(reading.XYZ(3)), ...
        repeat(reading.xyzMethod),repeat(reading.xyzUnits), ...
        repeat(reading.observerId),repeat(reading.spectralQuantity), ...
        repeat(reading.spectralUnits),repmat(synthetic,count,1),repeat(warnings), ...
        repeat(reading.matlabVersion),number(reading.durationSeconds), ...
        repeat(batchInfo.startedAtUTC),repeat(batchInfo.completedAtUTC), ...
        number(batchInfo.elapsedSeconds),'VariableNames',names);
end
if ~isempty(parts), data = vertcat(parts{:}); end
end
