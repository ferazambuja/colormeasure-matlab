function controls = settingsCatalog(values, layout, calibration)
%SETTINGSCATALOG Plain control/help values; never opens a port or sends commands.
% A readSettings catalog limits model capabilities. Dependent fields remain
% editable so callers can stage a new mode and its parameters together.
% Sources: CS-2000/2000A operating manual pp.26-33,43-48,54-55;
% communication specification Rev.7 pp.15-40,87-89. See docs/drivers/cs2000/settings.md.
% Fernando Voltolini de Azambuja, 2026.
if nargin < 1, values = struct(); end
if nargin < 2, layout = 'unknown'; end
if nargin < 3, calibration = struct(); end
manual = 'https://www.konicaminolta.com/instruments/download/instruction_manual/display/pdf/cs-2000-2000a_instruction_eng.pdf';
protocol = 'https://www.konicaminolta.com.cn/instruments/download/software/driver/cs-20002000a_cs0700_eng.pdf';
controls = [ ...
    control('speedMode','Measurement speed','choice', ...
        choices(0:4,{'Normal','Fast','Multi-Normal','Manual','Multi-Fast'}),NaN,NaN, ...
        'Selects automatic exposure and averaging, or a fixed manual exposure.', ...
        'Normal favors low-light accuracy. Fast reduces low-light time. Multi modes average periodic light with unknown or unstable frequency.', ...
        'Fast can reduce low-light accuracy. Multi-Fast requires the modern layout. No mode automatically identifies the best setup.', ...
        'Automatic acquisition uses Multi-Normal with a 1-second multi interval.',source(manual,'p.29',protocol,'pp.17-22,87-89')); ...
    control('integrationTimeSeconds','Exposure / averaging interval (s)','number',choices([],{}),0.005,120, ...
        'Manual fixes exposure in seconds; Multi sets an averaging interval in whole seconds.', ...
        'Use Manual for a required fixed exposure, or Multi for periodic light whose frequency is unknown or unstable.', ...
        'Manual accepts 0.005-120 s in whole microseconds; Multi accepts 1-16 whole seconds. Total reading time also includes dark measurement and processing.', ...
        'The automatic recipe uses a 1-second Multi interval; dim targets can take longer.',source(manual,'p.29',protocol,'pp.17-22')); ...
    control('internalNDMode','Internal ND filter','choice',choices(0:2,{'Off','On','Auto'}),NaN,NaN, ...
        'Controls the neutral-density filter inside the instrument, separate from an attached external filter.', ...
        'Auto chooses attenuation from brightness. Fixed On or Off can keep filter state consistent during a luminance sweep.', ...
        'Manual permits only Off or On. Legacy nonmanual modes are fixed at Auto; modern modes permit all three.', ...
        'Automatic acquisition uses Auto. Changing to Manual requires a valid fixed ND selection.',source(manual,'pp.31-33,45',protocol,'pp.17-22')); ...
    control('syncMode','Synchronization','choice',choices(0:2,{'No Sync','Internal','External'}),NaN,NaN, ...
        'Matches exposure timing to periodic light; it does not discover the source frequency.', ...
        'Use Internal for a known frequency or External with a connected 5 V CMOS sync signal. For unknown or unstable frequency use No Sync with a Multi mode.', ...
        'A wrong Internal frequency can cause inaccurate measurements; External needs a suitable physical signal.', ...
        'Automatic acquisition uses No Sync; there is no protocol Auto-sync mode.',source(manual,'pp.26-29',protocol,'pp.15-16')); ...
    control('frequencyHz','Internal sync frequency (Hz)','number',choices([],{}),20,200, ...
        'The known repetition frequency entered for Internal synchronization.', ...
        'Set this only when the light source frequency is known, from 20.00 to 200.00 Hz in 0.01 Hz increments.', ...
        'This is a configured value, not measured refresh rate. It is unavailable in No Sync and External modes.', ...
        'No frequency is forced by the No Sync automatic recipe.',source(manual,'pp.26-27',protocol,'pp.15-16')); ...
    control('measurementAngleDegrees','Measurement angle (physical selector)','choice',choices([1 .2 .1],{'1 degree','0.2 degree','0.1 degree'}),NaN,NaN, ...
        'The physical aperture controls the measured area, independently of the colorimetric observer.', ...
        'Choose an aperture that fits within the focused target at the measurement distance. Change the physical selector only while idle, then read settings again.', ...
        'Software cannot move this selector. Smaller apertures have different low-light limits.', ...
        'The automatic recipe preserves the physical aperture.',source(manual,'pp.23,54-55',protocol,'p.23')); ...
    control('closeupLens','Close-up lens compensation','choice',choices(0:1,{'Standard (no close-up lens)','Close-up lens attached'}),NaN,NaN, ...
        'Selects compensation for the optional close-up lens; it does not detect or attach a lens.', ...
        'Use Close-up for small nearby targets only when the lens is attached and its supplied factors are registered.', ...
        'A wrong selection gives inaccurate measurements. Do not combine the optional close-up lens and external ND filter.', ...
        'Preserved unless explicitly overridden; there is no automatic accessory detection.',source(manual,'pp.43-45,54',protocol,'pp.31-35')); ...
    control('externalNDFilter','External ND compensation','choice',choices(0:2,{'None','ND 1/10','ND 1/100'}),NaN,NaN, ...
        'Selects compensation matching the physically attached external neutral-density filter.', ...
        'Use an external filter for high-luminance targets after registering its supplied correction factors.', ...
        'A wrong selection gives inaccurate measurements. Do not combine an external ND filter with the optional close-up lens.', ...
        'Preserved unless explicitly overridden; this does not insert or detect a filter.',source(manual,'pp.43-46',protocol,'pp.36-40')); ...
    control('userCalibrationChannel','User correction channel','choice',choices(0:10, ...
        [{'Ch00 (NON): manufacturer calibration'},arrayfun(@(n)sprintf('Ch%02d: name not read',n),1:10,'UniformOutput',false)]),NaN,NaN, ...
        'Ch00 uses manufacturer calibration without a user correction; populated Ch01-Ch10 apply stored user corrections.', ...
        'Select the existing channel prescribed for the experiment. Read settings reports only the current channel name; other channel names remain unread.', ...
        'Empty channels cannot be selected. Selection does not create, update or validate calibration.', ...
        'Preserved unless explicitly overridden; calibration authoring is separate.',source(manual,'pp.47-48',protocol,'pp.24-30'))];
controls(strcmp({controls.id},'measurementAngleDegrees')).available = false;
if isfield(values,'speedMode')
    speed = find(strcmp({controls.id},'speedMode'));
    if ~strcmp(layout,'modern')
        controls(speed).choices([controls(speed).choices.value] == 4) = [];
    end
end
if isfield(calibration,'name') && ~isempty(calibration.name) && isfield(values,'userCalibrationChannel')
    current = values.userCalibrationChannel;
    % A retained name cannot identify an unknown channel in a partial report.
    if isnumeric(current) && isreal(current) && isscalar(current) && ismember(current,1:10)
        channel = find(strcmp({controls.id},'userCalibrationChannel'));
        choice = find([controls(channel).choices.value]==current,1);
        controls(channel).choices(choice).label = sprintf('Ch%02d: %s',current,calibration.name);
    end
end
% Next-reading labels follow the requested speed, not a stale observation.
% The automatic acquisition recipe supplies Multi-Normal when not overridden.
[controls.editor]=deal(struct());
contexts=struct('value',num2cell(0:4),'name',{'Normal','Fast','Multi-Normal','Manual','Multi-Fast'}, ...
    'label',{'Interval not used','Interval not used','Multi averaging interval (s)', ...
    'Manual exposure (s)','Multi averaging interval (s)'}, ...
    'minimum',{NaN,NaN,1,0.005,1},'maximum',{NaN,NaN,16,120,16}, ...
    'integer',{false,false,true,false,true},'available',{false,false,true,true,true}, ...
    'meaning',{'Normal determines exposure automatically; clear the interval override.', ...
    'Fast determines exposure automatically; clear the interval override.', ...
    'Set the Multi averaging interval in whole seconds, from 1 to 16. This is not the total reading duration.', ...
    'Set a fixed Manual exposure from 0.005 to 120 seconds, in whole microseconds. Select a fixed internal ND mode too.', ...
    'Set the Multi averaging interval in whole seconds, from 1 to 16. This is not the total reading duration.'});
controls(strcmp({controls.id},'integrationTimeSeconds')).editor=struct( ...
    'kind','dependentNumber','setting','speedMode','defaultContext',2,'contexts',contexts, ...
    'incrementScale',1e6,'incrementTolerance',1e-6);
end

function item = control(id,label,type,options,minimum,maximum,meaning,whenToUse,tradeoff,normal,reference)
item = colormeasure.session.settingsControl(id,label,type,options,minimum,maximum,true, ...
    struct('meaning',meaning,'whenToUse',whenToUse,'tradeoff',tradeoff,'normal',normal,'source',reference));
end

function options = choices(values,labels)
options = struct('value',num2cell(values),'label',labels);
end

function reference = source(manual,manualPages,protocol,protocolPages)
reference = sprintf('Operating manual %s: %s ; Rev.7 %s: %s',manualPages,manual,protocolPages,protocol);
end
