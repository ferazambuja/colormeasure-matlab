function controls = settingsCatalog(model, capabilities, includeExpert)
% SETTINGSCATALOG Plain descriptions; constructing a catalog performs no I/O.
%   Dynamic accessory/aperture choices come only from the connected meter.
%   Fernando Voltolini de Azambuja, 2026. Sources: docs/drivers/pr/settings.md.
if nargin < 1, model = ''; end
if nargin < 2, capabilities = struct(); end
if nargin < 3, includeExpert = false; end
is670 = strcmp(model, 'PR-670');
source = 'PR-655/PR-670 manual Rev B, printed pp.107-112; docs/drivers/pr/settings.md';
emptyChoices = struct('value', {}, 'label', {});
controls = colormeasure.session.settingsControl();
add('exposureMilliseconds','Exposure','number',emptyChoices,0,6000,true, ...
    'Integration time. Zero lets the instrument choose the exposure.', ...
    'Use a fixed time when a repeatable integration interval is needed.', ...
    'Longer exposures take longer. PR-655 fixed times are 3-6000 ms; PR-670 times are 6-6000 ms, or up to 30000 ms in Extended sensitivity.', ...
    'The automatic recipe selects Adaptive (0). Applying that recipe without this override restores Adaptive.');
add('cycles','Cycles to average','number',emptyChoices,1,99,true, ...
    'Number of instrument measurements averaged into one returned spectrum.', ...
    'Increase for a stable target when repeated readings fluctuate.', ...
    'More cycles increase measurement time; exposure times cycles can exceed the measurement (M5) timeout.', ...
    'The automatic recipe uses one cycle. Applying that recipe without this override restores one cycle.');
add('syncMode','Synchronization','choice',choices({'none','auto','user'},{'None','Automatic','User frequency'}),NaN,NaN,true, ...
    'With adaptive exposure, synchronization aligns integration with source modulation.', ...
    'Use Automatic for detectable periodic modulation, User frequency for a known frequency, or None for a known nonmodulated source.', ...
    'Detection may fail for weak signals or unsupported frequencies. None can reduce repeatability on periodic sources; fixed exposure does not gain adaptive synchronization.', ...
    'The automatic recipe selects Automatic. Applying that recipe without this override restores automatic synchronization.');
add('syncFrequencyHz','User sync frequency (Hz)','number',emptyChoices,20,400,true, ...
    'Frequency used when synchronization is set to User frequency.', ...
    'Enter a known integer source frequency and select User frequency.', ...
    'An incorrect frequency can bias measurements of a periodic source. This setting alone does not activate User frequency.', ...
    'Clear the sync-mode override to return to Automatic. The stored user frequency is otherwise retained.');
accessories = struct('id',{},'name',{},'type',{});
if isfield(capabilities,'accessories'), accessories = capabilities.accessories; end
primary = accessoryChoices(accessories,'Primary'); addon = accessoryChoices(accessories,'Addon');
add('primaryAccessoryId','Primary optical accessory','choice',primary,NaN,NaN,~isempty(primary), ...
    'Selects the calibration for the fitted primary lens or receptor.', ...
    'Change only after fitting the corresponding calibrated accessory.', ...
    'A calibration selection cannot detect or install physical optics; the wrong selection changes the meaning of readings.', ...
    'The normal recipe preserves optics. Clearing an override does not restore an earlier accessory; select that fitted accessory explicitly.');
for slot=1:3
    add(sprintf('addon%dId',slot),sprintf('Add-on accessory %d',slot),'choice',addon,NaN,NaN,~isempty(addon), ...
        'Selects a calibrated add-on, such as a neutral-density filter, for this slot.', ...
        'Use only for an add-on physically fitted with the primary accessory.', ...
        'The manual does not establish an add-on clearing command; None is not offered as an assumed code.', ...
        'The normal recipe preserves accessory slots. Clearing an override stops future writes but does not remove the instrument selection.');
end
apertures = emptyChoices;
if isfield(capabilities,'apertures')
    for index=1:numel(capabilities.apertures)
        entry=capabilities.apertures(index);
        apertures(end+1)=struct('value',entry.id,'label',entry.name); %#ok<AGROW>
    end
end
add('apertureId','Measuring aperture (PR-670)','choice',apertures,NaN,NaN,is670&&~isempty(apertures), ...
    'Selects a calibrated PR-670 measuring aperture; PR-655 aperture is not software-selectable.', ...
    'Choose an aperture that fits within the target area.', ...
    'Smaller apertures collect less light and may require longer exposures. PR-670 support remains tentative.', ...
    'The normal recipe preserves the aperture. Select the previous aperture explicitly to restore it.');
add('sensitivityMode','Sensitivity range (PR-670)','choice',choices({'standard','extended'},{'Standard','Extended'}),NaN,NaN,is670, ...
    'Sets the PR-670 exposure ceiling: 6000 ms in Standard or 30000 ms in Extended.', ...
    'Extended can help with dim targets.', ...
    'Extended permits substantially longer measurements; scripts can raise the measurement (M5) timeout when connecting.', ...
    'The normal recipe preserves this range. Select Standard explicitly to return to its shorter ceiling.');
add('smartDark','Smart Dark (PR-670)','choice',choices({0,1},{'Standard dark measurement','Smart Dark'}),NaN,NaN,is670, ...
    'Smart Dark reuses detector dark data when successive exposure times match.', ...
    'Consider for repeated measurements at stable exposure and conditions.', ...
    'Reusing dark data can reduce measurement time but does not acquire a fresh dark for every reading.', ...
    'The normal recipe preserves this mode. Select Standard dark measurement to disable reuse; this is separate from shutter control.');
if includeExpert
    add('photometricUnits','Photometric report units','choice',choices({'english','metric'},{'English','Metric (SI)'}),NaN,NaN,true, ...
        'Selects units for applicable instrument photometric reports.', ...
        'Use when requesting native photometric reports.', ...
        'SU1 is not an M5 units code and does not establish spectral quantity or scale.', ...
        'No automatic change is made. Select the previous unit system explicitly.');
    add('instrumentObserver','Instrument observer','choice',choices({2,10},{'CIE 1931 2 degree','CIE 1964 10 degree'}),NaN,NaN,true, ...
        'Selects the observer used by instrument photometric/colorimetric reports.', ...
        'Use for native reports requiring a particular observer.', ...
        'This does not change the workflow XYZ calculated from M5 using CIE 1931 2 degree.', ...
        'No automatic change is made. Select 2 explicitly to return native reports to 2 degrees.');
    add('shutterMode','Measure shutter','choice',choices({'closeAfter','alwaysOpen'},{'Close after measurement','Always open'}),NaN,NaN,true, ...
        'Controls closure of the measure shutter and acquisition of a dark measurement.', ...
        'Expert control only; the manual recommends closing after measurement.', ...
        'Always open skips dark measurements. D602 Smart Dark does not read this setting back.', ...
        'No automatic change is made. Select Close after measurement (SZ0) explicitly; acknowledgement is not independent readback.');
end
% Bounds describe model capability so Extended and a longer exposure can be
% staged together. settingsCommands validates their merged target state.
if is670
    controls(strcmp({controls.id},'exposureMilliseconds')).maximum=30000;
end
% The UI separates the special adaptive value from a fixed duration. These
% are presentation/validation facts, not additional instrument settings.
[controls.editor]=deal(struct());
minimum=3;if is670,minimum=6;end
controls(strcmp({controls.id},'exposureMilliseconds')).editor=struct( ...
    'kind','automaticNumber','automaticValue',0,'automaticLabel','Adaptive', ...
    'fixedLabel','Fixed','fixedMinimum',minimum,'integer',true,'unit','ms');
if is670
    observed='';if isfield(capabilities,'sensitivityMode'),observed=capabilities.sensitivityMode;end
    controls(strcmp({controls.id},'exposureMilliseconds')).editor.ceiling=struct( ...
        'setting','sensitivityMode','observed',observed,'extendedValue','extended', ...
        'standardMaximum',6000,'extendedMaximum',30000);
end
    function add(id,label,type,items,minimum,maximum,available,meaning,when,tradeoff,normal)
        controls(end+1,1)=colormeasure.session.settingsControl(id,label,type,items, ...
            minimum,maximum,logical(available), ...
            struct('meaning',meaning,'whenToUse',when,'tradeoff',tradeoff,'normal',normal,'source',source));
    end
end
function items=choices(values,labels)
items=struct('value',values,'label',labels);
end
function items=accessoryChoices(entries,type)
items=struct('value',{},'label',{});
for index=1:numel(entries)
    if strcmpi(entries(index).type,type)
        items(end+1)=struct('value',entries(index).id,'label',entries(index).name); %#ok<AGROW>
    end
end
end
