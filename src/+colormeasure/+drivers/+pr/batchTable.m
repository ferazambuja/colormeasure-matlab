function data = batchTable(measurements, batchInfo)
% BATCHTABLE PR spectral export; instrument-specific fields stay in this adapter.
%   A batch without readings gives the same columns with no rows.
%   IsSynthetic records the producer's explicit generated-data flag. False
%   does not establish physical validation, calibration or measurement accuracy.
%   Fernando Voltolini de Azambuja, 2026.
names = {'MeasurementIndex', 'MeasurementName', 'Notes', 'StartedAtUTC', 'CompletedAtUTC', ...
    'DeviceType', 'Port', 'UnitsCode', 'Wavelength_nm', 'SpectralReading', ...
    'Computed_X', 'Computed_Y', 'Computed_Z', 'IntegratedSpectralReading', ...
    'PeakWavelength_nm', 'InstrumentIntegratedReading', 'IntegratedPhotonReading', ...
    'SpectralUnits', 'XYZMethod', 'MATLABVersion', 'MeasurementDurationSeconds', ...
    'BatchStartedAtUTC', 'BatchCompletedAtUTC', 'BatchElapsedSeconds', ...
    'StartedAtLocal', 'CompletedAtLocal', 'LocalTimeZone', ...
    'BatchStartedAtLocal', 'BatchCompletedAtLocal', 'BatchLocalTimeZone', 'IsSynthetic'};
types = repmat({'cell'}, 1, numel(names));
types([1 8:17 21 24]) = {'double'};
types{end} = 'logical';
data = table('Size', [0 numel(names)], 'VariableTypes', types, 'VariableNames', names);
tables = cell(numel(measurements), 1);
for index = 1:numel(measurements)
    tables{index} = readingTable(measurements(index), index, batchInfo, names);
end
if ~isempty(tables), data = vertcat(tables{:}); end
end

function data = readingTable(measurement, index, batchInfo, names)
assert(isfield(measurement,'isSynthetic')&&islogical(measurement.isSynthetic)&& ...
    isscalar(measurement.isSynthetic),'PR655:ExportProvenance', ...
    'PR CSV requires an explicit scalar logical isSynthetic value from the reading producer.');
count = numel(measurement.lambda);
spectrum = colormeasure.drivers.pr.spectrumOf(measurement);
repeatText = @(value) repmat({char(value)}, count, 1);
repeatNumber = @(value) repmat(value, count, 1);
% The local times and zone are those captured with each reading and batch.
data = table(repeatNumber(index), repeatText(measurement.name), repeatText(measurement.notes), ...
    repeatText(measurement.startedAtUTC), repeatText(measurement.completedAtUTC), ...
    repeatText(measurement.deviceType), repeatText(measurement.port), ...
    repeatNumber(measurement.unitsCode), measurement.lambda(:), spectrum(:), ...
    repeatNumber(measurement.XYZ(1)), repeatNumber(measurement.XYZ(2)), ...
    repeatNumber(measurement.XYZ(3)), repeatNumber(measurement.totalRadiance), ...
    repeatNumber(measurement.peakWavelength), ...
    repeatNumber(measurement.instrumentTotalRadiance), ...
    repeatNumber(measurement.integratedPhotonRadiance), ...
    repeatText(measurement.spectralUnits), repeatText(measurement.xyzMethod), ...
    repeatText(measurement.matlabVersion), repeatNumber(measurement.durationSeconds), ...
    repeatText(batchInfo.startedAtUTC), repeatText(batchInfo.completedAtUTC), ...
    repeatNumber(batchInfo.elapsedSeconds), ...
    repeatText(measurement.startedAtLocal), repeatText(measurement.completedAtLocal), ...
    repeatText(measurement.localTimeZone), ...
    repeatText(batchInfo.startedAtLocal), repeatText(batchInfo.completedAtLocal), ...
    repeatText(batchInfo.localTimeZone), repeatNumber(measurement.isSynthetic), ...
    'VariableNames', names);
end
