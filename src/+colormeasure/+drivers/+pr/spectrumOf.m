function values=spectrumOf(reading)
%SPECTRUMOF Validate the spectrum in one current PR reading.
%   PR readings store spectral values in radiance and wavelengths in lambda.
%   Fernando Voltolini de Azambuja, 2026.
assert(isstruct(reading) && isscalar(reading) && isfield(reading,'radiance') && ...
    isnumeric(reading.radiance) && isreal(reading.radiance) && ...
    isvector(reading.radiance) && ~isempty(reading.radiance) && ...
    all(isfinite(reading.radiance(:))), ...
    'PR655:SpectrumField','The reading needs one finite real radiance vector.');
values=reading.radiance;
end
