function yes=isTextInput(control)
%ISTEXTINPUT Do not turn typing in a draft field into a measurement command.
yes=~isempty(control)&&isgraphics(control)&& ...
    ((isprop(control,'Style')&&strcmp(control.Style,'edit'))|| ...
    isa(control,'matlab.ui.control.EditField')||isa(control,'matlab.ui.control.NumericEditField')|| ...
    isa(control,'matlab.ui.control.TextArea'));
end
