function value=settingLabel(key)
%SETTINGLABEL One presentation label for a retained material setup fact.
names=struct('serial','Instrument serial number','accessory','Fitted accessory','aperture','Fitted aperture', ...
    'primaryAccessoryId','Primary accessory ID','addon1Id','Accessory add-on 1 ID', ...
    'addon2Id','Accessory add-on 2 ID','addon3Id','Accessory add-on 3 ID','apertureId','Aperture ID', ...
    'filter1','Filter 1','filter2','Filter 2','filter3','Filter 3','captureFilters','Fitted filters', ...
    'measurementAngleDegrees','Measurement angle (degrees)','closeupLens','Close-up lens', ...
    'externalNDFilter','External ND filter', ...
    'spectralGrid','Spectral wavelength grid (nm)');
if isfield(names,key)
    value=names.(key);
else
    value=regexprep(key,'([a-z])([A-Z])','$1 $2');value=strrep(value,'_',' ');
    if ~isempty(value),value(1)=upper(value(1));end
end
end
