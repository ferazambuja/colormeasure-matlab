function [chart,definition,indices]=validateSnapshot(info,readings)
%VALIDATESNAPSHOT Validate a retained chart and every selected reading link.
% Validate every consumed link before constructing subsets or invoking an
% adapter. An invalid later pass must not partly run an earlier pass's hook.
[chart,definition,indices]=validateSnapshotData(info,readings,true);
end

function [chart,definition,indices]=validateSnapshotData(info,readings,checkReadingIds)
identifier='Measurement:ChartExport';
colormeasure.chart.assertDirectSource(info,readings);
assert(isfield(info,'chart')&&isstruct(info.chart)&&isscalar(info.chart)&& ...
    all(isfield(info.chart,{'format','version','runId','segmentId','parentSegmentId','sources','definition','passes'})), ...
    identifier,'The batch must contain one complete guided-chart snapshot.');
chart=info.chart;
chartFields={'format','version','runId','segmentId','parentSegmentId','sources', ...
    'definition','referenceData','orientation','traversal','currentCell','paused', ...
    'activePass','passes','pendingContext','revision','savedRevision', ...
    'pendingSample','freeSample','chartSample','continuation'};
assert(all(ismember(fieldnames(chart),chartFields)),identifier, ...
    'The saved chart contains fields outside the current direct chart schema.');
assert(colormeasure.session.isText(chart.format)&&strcmp(chart.format,'guided-chart')&& ...
    isnumeric(chart.version)&&isreal(chart.version)&&isscalar(chart.version)&& ...
    isfinite(chart.version)&&chart.version==colormeasure.chart.Run.FormatVersion,identifier, ...
    'This saved chart format is unsupported. Its ordinary MAT values remain available for plain load inspection; the original data was not changed.');
assert(nonemptyText(chart.runId)&&nonemptyText(chart.segmentId), ...
    identifier,'Guided-chart run and segment identities must be nonempty scalar text.');
assert(isfield(info,'segmentId')&&nonemptyText(info.segmentId)&&strcmp(info.segmentId,chart.segmentId), ...
    identifier,'The saved batch and chart must identify the same segment.');
assert(all(isfield(info,{'configuration','catalogIdentity'}))&& ...
    isstruct(info.configuration)&&isscalar(info.configuration)&& ...
    isstruct(info.catalogIdentity)&&isscalar(info.catalogIdentity)&& ...
    all(isfield(info.catalogIdentity,{'model','key'}))&&colormeasure.session.isText(info.catalogIdentity.model)&& ...
    nonemptyText(info.catalogIdentity.key), ...
    'Measurement:ChartReference','The chart must retain its original acquisition owner configuration and model catalog.');
validateSources(chart);
% Check original native reading IDs once across the flattened owner set.
% Sources without native IDs still retain their segment and append-index links.
if checkReadingIds,validateReadingIds(chart,readings);end
for n=1:numel(readings),validateReading(readings(n));end
if ~isempty(chart.sources)
    % The registry is one ordered, flattened ancestry chain. Validate its
    % immediate parent with a strictly shorter registry, never nested graphs.
    source=chart.sources(end);parent=source.batchInfo;
    parent.chart.sources=chart.sources(1:end-1);
    validateSnapshotData(parent,source.measurements,false);
end
try
    definition=colormeasure.chart.validateDefinition(chart.definition);
catch cause
    problem=MException(identifier,'The saved chart definition is invalid: %s',cause.message);
    throw(addCause(problem,cause));
end
passFields={'id','context','attempts','selectedAttempt'};
assert(isstruct(chart.passes)&&~isempty(chart.passes)&&isvector(chart.passes)&& ...
    isequal(sort(fieldnames(chart.passes)),sort(passFields(:))), ...
    identifier,'Guided-chart passes must use the current direct chart schema.');
validateContinuation(chart);
cellCount=numel(definition.cells);indices=cell(1,numel(chart.passes));
passIds=cell(1,numel(chart.passes));
fields={'cellIndex','row','column','context','acceptedContext','name','notes', ...
    'startedAtUTC','completedAtUTC','status','reason','readingIndices','segmentId'};
for p=1:numel(chart.passes)
    pass=chart.passes(p);
    assert(nonemptyText(pass.id)&&isstruct(pass.context)&&isscalar(pass.context)&&colormeasure.session.isPlainData(pass.context), ...
        identifier,'A chart pass needs a text identity and an ordinary scalar context record.');
    passIds{p}=char(pass.id);
    assert(~any(strcmp(passIds(1:p-1),passIds{p})),identifier, ...
        'Guided-chart pass identities must be unique.');
    assert(isstruct(pass.attempts)&&(isempty(pass.attempts)||isvector(pass.attempts))&& ...
        isequal(sort(fieldnames(pass.attempts)),sort(fields(:))), ...
        identifier,'Chart attempts must use the current direct chart schema.');
    chosen=pass.selectedAttempt;
    assert(isnumeric(chosen)&&isreal(chosen)&&isvector(chosen)&&numel(chosen)==cellCount&& ...
        all(isfinite(chosen))&&all(chosen==fix(chosen))&&all(chosen>=0)&&all(chosen<=numel(pass.attempts)), ...
        'Measurement:ChartReference','Selected attempts must provide one valid index or zero for every chart cell.');
    observations={};
    for k=1:numel(pass.attempts)
        attempt=pass.attempts(k);
        assert(indexValue(attempt.cellIndex,cellCount),'Measurement:ChartReference', ...
            'A chart attempt has an invalid canonical cell reference.');
        for field={'name','notes','status','reason','segmentId','startedAtUTC','completedAtUTC'}
            assert(colormeasure.session.isText(attempt.(field{1})),identifier, ...
                'Chart attempt %s must be scalar nonmissing text.',field{1});
        end
        cellValue=definition.cells(attempt.cellIndex);
        assert(all(isfield(attempt,{'row','column'}))&& ...
            indexValue(attempt.row,definition.rows)&&indexValue(attempt.column,definition.columns)&& ...
            attempt.row==cellValue.row&&attempt.column==cellValue.column&& ...
            strcmp(attempt.name,cellValue.coordinate),'Measurement:ChartReference', ...
            'A retained attempt must preserve its original canonical row, column and coordinate name.');
        assert(any(strcmp(attempt.status,{'started','completed','failed','cancelled','unresolved'})), ...
            identifier,'A chart attempt has an unsupported outcome.');
        links=attempt.readingIndices;
        assert(isnumeric(links)&&isreal(links)&&(isempty(links)||isvector(links))&& ...
            all(isfinite(links))&&all(links==fix(links))&&all(links>=1)&&numel(unique(links))==numel(links), ...
            'Measurement:ChartReference','Every retained chart reading link must be a unique positive integer.');
        if strcmp(attempt.status,'started')
            assert(isempty(links),'Measurement:ChartReference','An unfinished attempt cannot claim retained observations.');
        elseif strcmp(attempt.status,'completed')
            assert(isscalar(links),'Measurement:ChartReference','A completed chart spot must retain exactly one reading.');
        end
        assert(strcmp(attempt.segmentId,chart.segmentId)||any(strcmp({chart.sources.segmentId},attempt.segmentId)), ...
            'Measurement:ChartReference','A chart attempt must resolve to its current or inherited source segment.');
        if ~strcmp(attempt.segmentId,chart.segmentId)
            source=chart.sources(strcmp({chart.sources.segmentId},attempt.segmentId));
            original=source.batchInfo.chart.passes;
            match=find(strcmp({original.id},pass.id));
            assert(isscalar(match),'Measurement:ChartReference','An inherited attempt must retain its original pass identity.');
            history=original(match).attempts;
            assert(any(arrayfun(@(entry)isequaln(entry,attempt),history)), ...
                'Measurement:ChartReference','Inherited attempts must remain identical to their frozen source history.');
        end
        for link=reshape(links,1,[])
            identity=sprintf('%s:%d',attempt.segmentId,link);
            assert(~any(strcmp(observations,identity)),'Measurement:ChartReference', ...
                'One original reading cannot represent more than one attempt within a chart pass.');
            observations{end+1}=identity; %#ok<AGROW>
            colormeasure.chart.resolveReading(chart,readings,attempt,link);
        end
    end
    selectedCells=find(chosen>0);links=zeros(1,numel(selectedCells));
    for k=1:numel(selectedCells)
        cellIndex=selectedCells(k);attempt=pass.attempts(chosen(cellIndex));
        assert(attempt.cellIndex==cellIndex&&strcmp(attempt.status,'completed')&& ...
            isnumeric(attempt.readingIndices)&&isscalar(attempt.readingIndices),'Measurement:ChartReference', ...
            'A selected chart attempt must name its own cell and exactly one successful retained reading.');
        assert(isstruct(attempt.acceptedContext)&&isscalar(attempt.acceptedContext)&& ...
            ~isempty(fieldnames(attempt.acceptedContext))&&colormeasure.session.isPlainData(attempt.acceptedContext), ...
            identifier,'A selected chart attempt must retain its own ordinary accepted context.');
        reading=colormeasure.chart.resolveReading(chart,readings,attempt);
        owner=info;
        if ~strcmp(attempt.segmentId,chart.segmentId)
            owner=chart.sources(strcmp({chart.sources.segmentId},attempt.segmentId)).batchInfo;
        end
        colormeasure.chart.validateAcceptedContext(owner,reading,attempt.acceptedContext,pass.context);
        links(k)=attempt.readingIndices;
    end
    indices{p}=links;
end
end

function validateContinuation(chart)
identifier='Measurement:ChartReference';
if isempty(chart.sources)
    assert(~isfield(chart,'continuation'),identifier, ...
        'An original chart must not claim a linked continuation record.');
    return
end
fields={'sourceSegmentId','sourcePassId','action','declarations','declarationEvidence', ...
    'sourcePendingPassId','sourcePendingContext'};
assert(isfield(chart,'continuation')&&isstruct(chart.continuation)&&isscalar(chart.continuation)&& ...
    isequal(sort(fieldnames(chart.continuation)),sort(fields(:)))&& ...
    colormeasure.session.isPlainData(chart.continuation),identifier, ...
    'A linked chart must retain exactly one complete current continuation record.');
record=chart.continuation;parent=chart.sources(end).batchInfo.chart;
assert(nonemptyText(record.sourceSegmentId)&&strcmp(record.sourceSegmentId,chart.parentSegmentId)&& ...
    nonemptyText(record.sourcePassId)&&nonemptyText(record.sourcePendingPassId)&& ...
    colormeasure.session.isText(record.action)&&any(strcmp(record.action,{'continue','new-pass'})), ...
    identifier,'Continuation action and source identity must bind the immediate frozen parent.');
parentIds={parent.passes.id};sourcePass=find(strcmp(parentIds,record.sourcePassId));
assert(isscalar(sourcePass)&&strcmp(record.sourcePendingPassId,parent.passes(parent.activePass).id)&& ...
    isequaln(record.sourcePendingContext,parent.pendingContext),identifier, ...
    'Continuation pass and pending context must match the immediate frozen parent capture.');
assert(isstruct(record.declarations)&&isscalar(record.declarations)&& ...
    colormeasure.session.isPlainData(record.declarations),identifier, ...
    'Continuation declarations must remain one ordinary scalar record.');
% Reuse the declaration owner without re-testing initial target eligibility
% against a pass context that later acquisitions or new passes can change.
% Target-only observable keys can belong to a legitimate new-pass setup.
before=parent.passes(sourcePass).context;declarationContext=before;
try
    declarationContext.requiredMaterial=union(before.requiredMaterial,fieldnames(record.declarations));
    decision=colormeasure.chart.continuity(before,declarationContext,record.declarations);
catch cause
    problem=MException(identifier,'The retained continuation declarations are invalid: %s',cause.message);
    throw(addCause(problem,cause));
end
evidence=record.declarationEvidence;evidenceFields={'key','value','certainty','scope'};
assert(isstruct(evidence)&&(isempty(evidence)||isvector(evidence))&& ...
    isequal(sort(fieldnames(evidence)),sort(evidenceFields(:)))&& ...
    isequaln(evidence,decision.declarations),identifier, ...
    'Continuation declaration evidence must retain exact keys, values and operator-declared scope.');
assert(isfield(chart,'activePass')&&indexValue(chart.activePass,numel(chart.passes))&& ...
    all(arrayfun(@(pass)nonemptyText(pass.id),chart.passes)),identifier, ...
    'A linked chart must retain valid pass identities and its active pass.');
ids={chart.passes.id};parentCount=numel(parentIds);
assert(numel(ids)>=parentCount&&isequal(ids(1:parentCount),parentIds),identifier, ...
    'Inherited pass identities must retain the immediate parent''s order.');
activeId=chart.passes(chart.activePass).id;
if any(strcmp(parentIds,activeId))
    assert(strcmp(record.action,'continue')&&strcmp(activeId,record.sourcePassId),identifier, ...
        'An active inherited pass must be the declared continued source pass.');
end
for p=1:parentCount
    pass=chart.passes(p);history=parent.passes(p).attempts;
    assert(isstruct(pass.attempts)&&numel(pass.attempts)>=numel(history)&& ...
        (isempty(history)||isequaln(pass.attempts(1:numel(history)),history)),identifier, ...
        'Inherited attempts must retain their immediate parent''s frozen history.');
    if isempty(pass.attempts),continue;end
    assert(isfield(pass.attempts,'segmentId'),identifier,'Inherited attempts must identify their original segment.');
    current=arrayfun(@(attempt)colormeasure.session.isText(attempt.segmentId)&& ...
        strcmp(attempt.segmentId,chart.segmentId),pass.attempts);
    assert(~any(current)||(strcmp(record.action,'continue')&&strcmp(pass.id,record.sourcePassId)), ...
        identifier,'Current-segment attempts in inherited passes require the declared continued source pass.');
end
end

function validateSources(chart)
identifier='Measurement:ChartReference';
fields=fieldnames(colormeasure.chart.emptySources());
assert(colormeasure.session.isText(chart.parentSegmentId)&&isstruct(chart.sources)&& ...
    (isempty(chart.sources)||isvector(chart.sources))&& ...
    numel(chart.sources)<=colormeasure.chart.Run.MaxInheritedSegments&& ...
    isequal(sort(fieldnames(chart.sources)),sort(fields))&&colormeasure.session.isPlainData(chart.sources), ...
    identifier,'Source segments must be one bounded, ordinary, flattened registry.');
parent='';seen={chart.segmentId};
for source=reshape(chart.sources,1,[])
    assert(isstruct(source.batchInfo)&&isscalar(source.batchInfo)&& ...
        all(isfield(source.batchInfo,{'segmentId','chart','continuationGuard'}))&& ...
        isstruct(source.batchInfo.chart)&&isscalar(source.batchInfo.chart)&& ...
        all(isfield(source.batchInfo.chart,{'parentSegmentId','sources','runId','definition','referenceData','passes','activePass','pendingContext'}))&& ...
        isstruct(source.batchInfo.chart.passes)&& ...
        indexValue(source.batchInfo.chart.activePass,numel(source.batchInfo.chart.passes))&& ...
        isstruct(source.batchInfo.chart.pendingContext)&& ...
        (isempty(source.batchInfo.chart.pendingContext)||isscalar(source.batchInfo.chart.pendingContext)), ...
        identifier,'Every inherited segment needs its complete frozen chart and batch metadata.');
    assert(nonemptyText(source.segmentId)&&~any(strcmp(seen,source.segmentId))&& ...
        colormeasure.session.isText(source.parentSegmentId)&&strcmp(source.parentSegmentId,parent)&& ...
        isstruct(source.measurements)&&(isempty(source.measurements)||isvector(source.measurements))&& ...
        isstruct(source.batchInfo)&&isscalar(source.batchInfo)&& ...
        all(isfield(source.batchInfo,{'segmentId','chart','continuationGuard'}))&& ...
        strcmp(source.segmentId,source.batchInfo.segmentId)&& ...
        strcmp(source.parentSegmentId,source.batchInfo.chart.parentSegmentId)&& ...
        isempty(source.batchInfo.chart.sources)&&strcmp(source.batchInfo.chart.runId,chart.runId)&& ...
        isequaln(source.batchInfo.chart.definition,chart.definition)&& ...
        isfield(chart,'referenceData')&&isequaln(source.batchInfo.chart.referenceData,chart.referenceData)&& ...
        ischar(source.sourceSha256)&&~isempty(regexp(source.sourceSha256,'^[0-9a-f]{64}$','once')), ...
        identifier,'Source identities, ancestry, frozen definition and byte witnesses must agree.');
    seen{end+1}=source.segmentId;parent=source.segmentId; %#ok<AGROW>
end
assert(strcmp(parent,chart.parentSegmentId),identifier,'The declared parent must equal the final ancestor.');
end

function validateReadingIds(chart,readings)
ids={};
owners=[{readings} {chart.sources.measurements}];
for n=1:numel(owners)
    for reading=reshape(owners{n},1,[])
        id=colormeasure.session.textField(reading,'readingId');
        if isempty(id),continue;end
        ids{end+1}=id; %#ok<AGROW>
    end
end
assert(numel(unique(ids))==numel(ids),'Measurement:ChartReference', ...
    'Original reading identities must be unique across current and inherited segments.');
end

function validateReading(reading)
colormeasure.session.validateReading(reading);
if isfield(reading,'XYZ')
    xyz=reading.XYZ;
    assert(isnumeric(xyz)&&isreal(xyz)&&numel(xyz)==3&&all(isfinite(xyz(:))), ...
        'Measurement:ChartReference','A retained XYZ reading must contain three finite values.');
end
for key={'radiance','spectralData'}
    if ~isfield(reading,key{1})||isempty(reading.(key{1})),continue;end
    values=reading.(key{1});
    assert(isfield(reading,'lambda')&&isnumeric(values)&&isreal(values)&&isvector(values)&&all(isfinite(values(:)))&& ...
        isnumeric(reading.lambda)&&isreal(reading.lambda)&&isvector(reading.lambda)&& ...
        numel(reading.lambda)==numel(values)&&all(isfinite(reading.lambda(:)))&&all(diff(reading.lambda(:))>0), ...
        'Measurement:ChartReference','Retained spectral values must match their original finite increasing grid.');
end
colormeasure.chart.assertDirectSource(struct(),reading);
end

function yes=indexValue(value,maximum)
yes=isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&& ...
    value==fix(value)&&value>=1&&value<=maximum;
end

function yes=nonemptyText(value)
yes=colormeasure.session.isText(value)&&~isempty(strtrim(char(value)));
end
