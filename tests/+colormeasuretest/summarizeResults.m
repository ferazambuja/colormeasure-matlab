function summary = summarizeResults(results, expectedCount)
% SUMMARIZERESULTS Require the complete discovered suite to pass.
% Fernando Voltolini de Azambuja, 2026.
summary = struct('testCount',numel(results),'expectedTestCount',expectedCount, ...
    'passed',nnz([results.Passed]),'failed',nnz([results.Failed]), ...
    'incomplete',nnz([results.Incomplete] | ~([results.Passed] | [results.Failed])), ...
    'testDurationSeconds',sum([results.Duration]), ...
    'softwarePassed',false);
summary.softwarePassed = expectedCount > 0 && summary.testCount == expectedCount ...
    && summary.passed == expectedCount && summary.failed == 0 && summary.incomplete == 0;
end
